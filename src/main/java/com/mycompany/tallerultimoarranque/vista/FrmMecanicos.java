    private void tblMecanicosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMecanicosMouseClicked
        // TODO add your handling code here:

        int filaVista = tblMecanicos.getSelectedRow();

        if (filaVista == -1) {
            return;
        }

        int fila = tblMecanicos.convertRowIndexToModel(filaVista);

        DefaultTableModel modelo
                = (DefaultTableModel) tblMecanicos.getModel();

        txtId.setText(
                String.valueOf(modelo.getValueAt(fila, 0))
        );

        txtNombre.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 1), "")
        );

        txtTelefono.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 2), "")
        );

        txtEspecialidad.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 3), "")
        );


    }//GEN-LAST:event_tblMecanicosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:

        if (txtId.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un mecánico de la tabla."
            );
            return;
        }

        int id;

        try {
            id = Integer.parseInt(txtId.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "El ID del mecánico no es válido."
            );
            return;
        }

        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String especialidad = txtEspecialidad.getText().trim();

        if (nombre.isEmpty() || especialidad.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "El nombre y la especialidad son obligatorios."
            );
            return;
        }

        if (nombre.length() > 120
                || telefono.length() > 20
                || especialidad.length() > 100) {

            JOptionPane.showMessageDialog(
                    this,
                    "Uno de los campos supera la longitud permitida."
            );
            return;
        }

        Mecanico mecanico = new Mecanico(
                id,
                nombre,
                telefono,
                especialidad
        );

        MecanicoDAO dao = new MecanicoDAO();

        try {

            if (dao.actualizar(mecanico)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Mecánico actualizado correctamente."
                );

                cargarMecanicos();

                txtId.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtEspecialidad.setText("");

                tblMecanicos.clearSelection();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se encontró el mecánico seleccionado."
                );
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al actualizar mecánico:\n"
                    + e.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:

        if (txtId.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un mecánico de la tabla."
            );
            return;
        }

        int id;

        try {
            id = Integer.parseInt(txtId.getText().trim());
        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El ID del mecánico no es válido."
            );
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar este mecánico?\n"
                + txtNombre.getText(),
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        MecanicoDAO dao = new MecanicoDAO();

        try {

            if (dao.eliminar(id)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Mecánico eliminado correctamente."
                );

                cargarMecanicos();

                txtId.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtEspecialidad.setText("");

                tblMecanicos.clearSelection();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se encontró el mecánico seleccionado."
                );
            }

        } catch (SQLException e) {

            if (e.getErrorCode() == 2292) {

                JOptionPane.showMessageDialog(
                        this,
                        "No se puede eliminar este mecánico "
                        + "porque tiene órdenes de trabajo asociadas.",
                        "Eliminación no permitida",
                        JOptionPane.WARNING_MESSAGE
                );

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Error al eliminar mecánico:\n"
                        + e.getMessage(),
                        "Error de base de datos",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        }


    }//GEN-LAST:event_btnEliminarActionPerformed

