    private TableRowSorter<DefaultTableModel> ordenador;

    private void filtrarMecanicos() {

        if (ordenador == null) {
            return;
        }

        String texto = txtBuscar.getText().trim();

        if (texto.isEmpty()) {
            ordenador.setRowFilter(null);
        } else {
            ordenador.setRowFilter(
                    RowFilter.regexFilter(
                            "(?i)" + Pattern.quote(texto)
                    )
            );
        }
    }

    private void configurarBusqueda() {

        txtBuscar.getDocument().addDocumentListener(
                new DocumentListener() {

            @Override
            public void insertUpdate(DocumentEvent e) {
                filtrarMecanicos();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                filtrarMecanicos();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                filtrarMecanicos();
            }
        });
    }

    private void cargarMecanicos() {

        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{
                    "ID",
                    "Nombre",
                    "Teléfono",
                    "Especialidad"
                }, 0) {

            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        MecanicoDAO dao = new MecanicoDAO();

        try {

            for (Mecanico mecanico : dao.listar()) {

                modelo.addRow(new Object[]{
                    mecanico.getId(),
                    mecanico.getNombre(),
                    mecanico.getTelefono(),
                    mecanico.getEspecialidad()
                });
            }

            tblMecanicos.setModel(modelo);

            ordenador = new TableRowSorter<>(modelo);
            tblMecanicos.setRowSorter(ordenador);

            filtrarMecanicos();
        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar mecánicos:\n"
                    + e.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

