    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:

        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String especialidad = txtEspecialidad.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar el nombre del mecánico.",
                    "Campo obligatorio",
                    JOptionPane.WARNING_MESSAGE
            );
            txtNombre.requestFocus();
            return;
        }

        if (especialidad.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar la especialidad del mecánico.",
                    "Campo obligatorio",
                    JOptionPane.WARNING_MESSAGE
            );
            txtEspecialidad.requestFocus();
            return;
        }

        if (nombre.length() > 120
                || telefono.length() > 20
                || especialidad.length() > 100) {

            JOptionPane.showMessageDialog(
                    this,
                    "Uno de los campos supera la longitud permitida."
            );
            return;
        }

        Mecanico mecanico = new Mecanico(
                0,
                nombre,
                telefono,
                especialidad
        );

        MecanicoDAO dao = new MecanicoDAO();

        try {

            if (dao.guardar(mecanico)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Mecánico registrado correctamente."
                );

                cargarMecanicos();

                txtId.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtEspecialidad.setText("");

                tblMecanicos.clearSelection();
                txtNombre.requestFocusInWindow();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se pudo registrar el mecánico."
                );
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al registrar mecánico:\n"
                    + e.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_btnGuardarActionPerformed

