    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        // TODO add your handling code here:

        int filaVista = tblClientes.getSelectedRow();

        if (filaVista == -1) {
            return;
        }

        int fila = tblClientes.convertRowIndexToModel(filaVista);

        DefaultTableModel modelo
                = (DefaultTableModel) tblClientes.getModel();

        txtId.setText(
                String.valueOf(modelo.getValueAt(fila, 0))
        );

        txtNombre.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 1), "")
        );

        txtTelefono.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 2), "")
        );

        txtDireccion.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 3), "")
        );

        txtCorreo.setText(
                java.util.Objects.toString(
                        modelo.getValueAt(fila, 4), "")
        );


    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:

        if (txtId.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un cliente de la tabla."
            );
            return;
        }

        int id;

        try {
            id = Integer.parseInt(txtId.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "El identificador del cliente no es válido."
            );
            return;
        }

        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String direccion = txtDireccion.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (nombre.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "El nombre del cliente es obligatorio."
            );
            return;
        }

        if (nombre.length() > 120
                || telefono.length() > 20
                || direccion.length() > 200
                || correo.length() > 150) {

            JOptionPane.showMessageDialog(
                    this,
                    "Uno de los campos supera la longitud permitida."
            );
            return;
        }

        Cliente cliente = new Cliente(
                id,
                nombre,
                telefono,
                direccion,
                correo
        );

        ClienteDAO dao = new ClienteDAO();

        try {

            if (dao.actualizar(cliente)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Cliente actualizado correctamente."
                );

                cargarClientes();

                txtId.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtDireccion.setText("");
                txtCorreo.setText("");

                tblClientes.clearSelection();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se encontró el cliente para actualizar."
                );
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al actualizar cliente:\n" + e.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:

        if (txtId.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un cliente de la tabla."
            );
            return;
        }

        int id;

        try {
            id = Integer.parseInt(txtId.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "El ID del cliente no es válido."
            );
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar este cliente?\n"
                + txtNombre.getText(),
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        ClienteDAO dao = new ClienteDAO();

        try {

            if (dao.eliminar(id)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Cliente eliminado correctamente."
                );

                cargarClientes();

                txtId.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtDireccion.setText("");
                txtCorreo.setText("");

                tblClientes.clearSelection();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se encontró el cliente seleccionado."
                );
            }

        } catch (SQLException e) {

            if (e.getErrorCode() == 2292) {

                JOptionPane.showMessageDialog(
                        this,
                        "No se puede eliminar este cliente "
                        + "porque tiene vehículos asociados.",
                        "Eliminación no permitida",
                        JOptionPane.WARNING_MESSAGE
                );

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Error al eliminar cliente:\n"
                        + e.getMessage(),
                        "Error de base de datos",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

