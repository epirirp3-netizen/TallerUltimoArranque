CREATE TABLE TALLER_CLIENTES (
    ID_CLIENTE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(20),
    DIRECCION VARCHAR2(200),
    CORREO VARCHAR2(150),
    CONSTRAINT PK_TCLIENTES PRIMARY KEY (ID_CLIENTE)
);

CREATE TABLE TALLER_MECANICOS (
    ID_MECANICO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(20),
    ESPECIALIDAD VARCHAR2(100),
    CONSTRAINT PK_TMECANICOS PRIMARY KEY (ID_MECANICO)
);

CREATE TABLE TALLER_VEHICULOS (
    ID_VEHICULO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PLACA VARCHAR2(20) NOT NULL,
    MARCA VARCHAR2(80) NOT NULL,
    MODELO VARCHAR2(80) NOT NULL,
    ANIO NUMBER(4),
    ID_CLIENTE NUMBER NOT NULL,
    CONSTRAINT PK_TVEHICULOS PRIMARY KEY (ID_VEHICULO),
    CONSTRAINT UQ_TVEHICULOS_PLACA UNIQUE (PLACA),
    CONSTRAINT FK_TVEHICULOS_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES TALLER_CLIENTES(ID_CLIENTE),
    CONSTRAINT CK_TVEHICULOS_ANIO CHECK (ANIO BETWEEN 1900 AND 2100)
);

CREATE TABLE TALLER_REPUESTOS (
    ID_REPUESTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(120) NOT NULL,
    DESCRIPCION VARCHAR2(300),
    PRECIO NUMBER(12,2) NOT NULL,
    CANTIDAD_DISPONIBLE NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TREPUESTOS PRIMARY KEY (ID_REPUESTO),
    CONSTRAINT CK_TREPUESTOS_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_TREPUESTOS_CANTIDAD CHECK (CANTIDAD_DISPONIBLE >= 0)
);

CREATE TABLE TALLER_SERVICIOS (
    ID_SERVICIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DESCRIPCION VARCHAR2(200) NOT NULL,
    COSTO_MANO_OBRA NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_TSERVICIOS PRIMARY KEY (ID_SERVICIO),
    CONSTRAINT CK_TSERVICIOS_COSTO CHECK (COSTO_MANO_OBRA >= 0)
);

CREATE TABLE TALLER_ORDENES (
    ID_ORDEN NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_VEHICULO NUMBER NOT NULL,
    ID_MECANICO NUMBER NOT NULL,
    DESCRIPCION_PROBLEMA VARCHAR2(500) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_INGRESO TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    FECHA_FINALIZACION TIMESTAMP,
    TOTAL_MANO_OBRA NUMBER(12,2) DEFAULT 0 NOT NULL,
    TOTAL_REPUESTOS NUMBER(12,2) DEFAULT 0 NOT NULL,
    COSTO_TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TORDENES PRIMARY KEY (ID_ORDEN),
    CONSTRAINT FK_TORDENES_VEHICULO
        FOREIGN KEY (ID_VEHICULO)
        REFERENCES TALLER_VEHICULOS(ID_VEHICULO),
    CONSTRAINT FK_TORDENES_MECANICO
        FOREIGN KEY (ID_MECANICO)
        REFERENCES TALLER_MECANICOS(ID_MECANICO),
    CONSTRAINT CK_TORDENES_ESTADO CHECK (
        ESTADO IN ('PENDIENTE','EN_PROCESO','FINALIZADA','CANCELADA')
    ),
    CONSTRAINT CK_TORDENES_COSTOS CHECK (
        TOTAL_MANO_OBRA >= 0 AND TOTAL_REPUESTOS >= 0 AND COSTO_TOTAL >= 0
    )
);

CREATE TABLE TALLER_DETALLE_SERVICIOS (
    ID_DETALLE_SERVICIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_ORDEN NUMBER NOT NULL,
    ID_SERVICIO NUMBER NOT NULL,
    COSTO_MANO_OBRA NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_TDET_SERVICIOS PRIMARY KEY (ID_DETALLE_SERVICIO),
    CONSTRAINT FK_TDS_ORDEN
        FOREIGN KEY (ID_ORDEN)
        REFERENCES TALLER_ORDENES(ID_ORDEN),
    CONSTRAINT FK_TDS_SERVICIO
        FOREIGN KEY (ID_SERVICIO)
        REFERENCES TALLER_SERVICIOS(ID_SERVICIO),
    CONSTRAINT CK_TDS_COSTO CHECK (COSTO_MANO_OBRA >= 0)
);

CREATE TABLE TALLER_DETALLE_REPUESTOS (
    ID_DETALLE_REPUESTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_ORDEN NUMBER NOT NULL,
    ID_REPUESTO NUMBER NOT NULL,
    CANTIDAD NUMBER(10) NOT NULL,
    PRECIO_UNITARIO NUMBER(12,2) NOT NULL,
    SUBTOTAL NUMBER(18,2) NOT NULL,
    CONSTRAINT PK_TDET_REPUESTOS PRIMARY KEY (ID_DETALLE_REPUESTO),
    CONSTRAINT FK_TDR_ORDEN
        FOREIGN KEY (ID_ORDEN)
        REFERENCES TALLER_ORDENES(ID_ORDEN),
    CONSTRAINT FK_TDR_REPUESTO
        FOREIGN KEY (ID_REPUESTO)
        REFERENCES TALLER_REPUESTOS(ID_REPUESTO),
    CONSTRAINT CK_TDR_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_TDR_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_TDR_SUBTOTAL CHECK (SUBTOTAL = CANTIDAD * PRECIO_UNITARIO)
);

CREATE TABLE TALLER_MOVIMIENTOS (
    ID_MOVIMIENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_REPUESTO NUMBER NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    CANTIDAD NUMBER(10) NOT NULL,
    FECHA TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    ID_ORDEN NUMBER,
    CONSTRAINT PK_TMOVIMIENTOS PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_TM_REPUESTO
        FOREIGN KEY (ID_REPUESTO)
        REFERENCES TALLER_REPUESTOS(ID_REPUESTO),
    CONSTRAINT FK_TM_ORDEN
        FOREIGN KEY (ID_ORDEN)
        REFERENCES TALLER_ORDENES(ID_ORDEN),
    CONSTRAINT CK_TM_TIPO CHECK (
        TIPO IN ('ABASTECIMIENTO','CONSUMO_ORDEN','DEVOLUCION_ORDEN')
    ),
    CONSTRAINT CK_TM_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_TM_ORDEN_TIPO CHECK (
        (TIPO = 'ABASTECIMIENTO' AND ID_ORDEN IS NULL)
        OR
        (TIPO IN ('CONSUMO_ORDEN','DEVOLUCION_ORDEN') AND ID_ORDEN IS NOT NULL)
    )
);

